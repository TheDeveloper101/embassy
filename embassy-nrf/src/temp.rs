//! Builtin temperature sensor driver.

use core::future::poll_fn;
use core::task::Poll;

use embassy_hal_internal::drop::OnDrop;
use embassy_sync::waitqueue::AtomicWaker;
#[cfg(feature = "time")]
use embassy_time::{Duration, with_timeout};

use abacus_registers::{heliod, process_register_block};

use crate::interrupt::InterruptExt;
use crate::peripherals::TEMP;
use crate::{Peri, interrupt, pac};

#[process_register_block(
    peripheral_name = "Nrf5xTemp",
    backend = external(pac::temp::Temp),
    states = [
        (Off, cost: 1),
        (Reading, *T*, cost: 5)
    ],
    transitions = [Off => Reading, Reading => Off]
)]
struct Nrf5xTempModel;

#[heliod(Nrf5xTempCost)]
mod checked {
    use super::*;
    use abacus_registers::heliod_operation;

    #[heliod_operation(
        peripheral = super::Nrf5xTempCost,
        from = Off,
        to = Reading,
        cost = 2
    )]
    pub(super) fn start(registers: &Nrf5xTempRegisters) {
        let peripheral = registers.peripheral();
        peripheral.intenset().write(|w| w.set_datardy(true));
        peripheral.tasks_start().write_value(1);
    }

    #[heliod_operation(
        peripheral = super::Nrf5xTempCost,
        from = Reading,
        to = Reading,
        cost = 1
    )]
    pub(super) fn handle_interrupt() {
        pac::TEMP.intenclr().write(|w| w.set_datardy(true));
        WAKER.wake();
    }

    #[heliod_operation(
        peripheral = super::Nrf5xTempCost,
        from = Reading,
        to = Reading,
        cost = 1
    )]
    pub(super) fn data_ready(registers: &Nrf5xTempRegisters) -> bool {
        registers.peripheral().events_datardy().read() != 0
    }

    #[heliod_operation(
        peripheral = super::Nrf5xTempCost,
        from = Reading,
        to = Off,
        cost = 2
    )]
    pub(super) fn complete(registers: &Nrf5xTempRegisters) -> i32 {
        let peripheral = registers.peripheral();
        peripheral.events_datardy().write_value(0);
        peripheral.temp().read() as i32
    }

    #[heliod_operation(
        peripheral = super::Nrf5xTempCost,
        from = Reading,
        to = Off,
        cost = 2
    )]
    pub(super) fn cancel(registers: &Nrf5xTempRegisters) {
        let peripheral = registers.peripheral();
        peripheral.tasks_stop().write_value(1);
        peripheral.events_datardy().write_value(0);
    }

    #[heliod_operation(
        peripheral = super::Nrf5xTempCost,
        from = Reading,
        to = Reading,
        cost = 1
    )]
    #[cfg(feature = "time")]
    async fn wait_ready(registers: &Nrf5xTempRegisters) {
        poll_fn(|cx| {
            WAKER.register(cx.waker());
            if data_ready(registers) {
                Poll::Ready(())
            } else {
                Poll::Pending
            }
        })
        .await
    }

    #[cfg(feature = "time")]
    async fn finish(registers: &Nrf5xTempRegisters) -> i32 {
        wait_ready(registers).await;
        complete(registers)
    }

    #[cfg(feature = "time")]
    pub(super) async fn read_celsius_x4(registers: &Nrf5xTempRegisters) -> i32 {
        start(registers);
        let on_drop = OnDrop::new(|| cancel(registers));
        let value = with_timeout(Duration::from_ticks(10), finish(registers))
            .await
            .expect("temperature measurement timed out");
        on_drop.defuse();
        value
    }
}

// This implementation supports the explicit `Reading` wrapper generated by
// the shared backend. The driver below uses the inferred wrapper instead.
impl abacus_registers::SyncState for Nrf5xTempRegisters<Reading> {
    type SyncStateEnum = Nrf5xTempStateEnum;

    fn sync_state(self) -> Self::SyncStateEnum {
        let peripheral = self.peripheral();
        peripheral.tasks_stop().write_value(1);
        peripheral.events_datardy().write_value(0);
        self.into_off().into()
    }
}

/// Interrupt handler.
pub struct InterruptHandler {
    _private: (),
}

impl interrupt::typelevel::Handler<interrupt::typelevel::TEMP> for InterruptHandler {
    unsafe fn on_interrupt() {
        checked::handle_interrupt();
    }
}

/// Builtin temperature sensor driver.
pub struct Temp<'d> {
    _peri: Peri<'d, TEMP>,
    registers: Nrf5xTempRegisters,
}

static WAKER: AtomicWaker = AtomicWaker::new();

impl<'d> Temp<'d> {
    /// Create a new temperature sensor driver.
    pub fn new(
        _peri: Peri<'d, TEMP>,
        _irq: impl interrupt::typelevel::Binding<interrupt::typelevel::TEMP, InterruptHandler> + 'd,
    ) -> Self {
        // Enable interrupt that signals temperature values
        interrupt::TEMP.unpend();
        unsafe { interrupt::TEMP.enable() };

        Self {
            _peri,
            // SAFETY: `Peri` provides exclusive ownership and a newly claimed
            // TEMP peripheral is not performing a measurement.
            registers: unsafe { Nrf5xTempRegisters::new(pac::TEMP) },
        }
    }

    /// Perform an asynchronous temperature measurement. The returned future
    /// can be awaited to obtain the measurement.
    ///
    /// The result is in units of 0.25 °C, i.e. divide by 4 to get °C.
    ///
    /// If the future is dropped, the measurement is cancelled.
    ///
    /// # Example
    ///
    /// ```no_run
    /// use embassy_nrf::{bind_interrupts, temp};
    /// use embassy_nrf::temp::Temp;
    ///
    /// bind_interrupts!(struct Irqs {
    ///     TEMP => temp::InterruptHandler;
    /// });
    ///
    /// # async {
    /// # let p: embassy_nrf::Peripherals = todo!();
    /// let mut t = Temp::new(p.TEMP, Irqs);
    /// let celsius: i32 = t.read_celsius_x4().await / 4;
    /// # };
    /// ```
    #[cfg(feature = "time")]
    pub async fn read_celsius_x4(&mut self) -> i32 {
        checked::read_celsius_x4(&self.registers).await
    }

    #[cfg(not(feature = "time"))]
    /// Perform an asynchronous temperature measurement without a timer.
    pub async fn read_celsius_x4(&mut self) -> i32 {
        let registers = &self.registers;
        checked::start(registers);
        let on_drop = OnDrop::new(|| checked::cancel(registers));
        let value = poll_fn(|cx| {
            WAKER.register(cx.waker());
            if checked::data_ready(registers) {
                Poll::Ready(checked::complete(registers))
            } else {
                Poll::Pending
            }
        })
        .await;
        on_drop.defuse();
        value
    }
}
